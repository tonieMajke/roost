import { setLang } from "../../src/i18n";

export type MainLang = "pl" | "en";
export type MainKey = keyof typeof pl;
const DICT: Record<MainLang, Record<string, string>> = { pl, en };

/** Polski tylko dla polskich ustawień systemu, reszta po angielsku (jak `resolveLang` w `src/i18n`). */
export const resolveMainLang = (pref: string | undefined, systemLocale: string | undefined): MainLang =>
  pref === "pl" || pref === "en" ? pref : systemLocale?.toLowerCase().startsWith("pl") ? "pl" : "en";

let current: MainLang = "pl";
export const getMainLang = (): MainLang => current;
export const setMainLang = (lang: MainLang): void => {
  current = lang === "en" ? "en" : "pl";
  // Moduły z `src/` (np. walidacja konfiguracji), które używają `t` z `src/i18n`, mówią tym samym językiem.
  setLang(current);
};

export function t(key: MainKey, params?: Record<string, string | number>): string {
  const text = DICT[current][key] ?? pl[key] ?? key;
  return params ? text.replace(/\{(\w+)\}/g, (m, n: string) => (n in params ? String(params[n]) : m)) : text;
}
